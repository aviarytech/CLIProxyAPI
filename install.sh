#!/usr/bin/env bash
# Installs the aviarytech CLIProxyAPI fork, its quota dashboard, and the
# Claude Code / Codex / T3 Code client wiring that routes through it.
#
#   curl -fsSL https://raw.githubusercontent.com/aviarytech/CLIProxyAPI/main/install.sh | bash
#
# Re-running is safe: it updates the source, rebuilds, and regenerates the
# client configs from your current ~/.claude and ~/.codex. Existing
# config.yaml, account tokens, and API keys are kept.
#
# Environment overrides:
#   CLIPROXY_REF      git ref to build (default: main)
#   CLIPROXY_SRC      source checkout (default: ~/.local/share/cliproxyapi)
#   CLIPROXY_BIN_DIR  where the `cliproxy` launcher goes (default: ~/.local/bin)
#   CLIPROXY_SERVICE  set to 1 on macOS to run cliproxy as a launchd agent
set -euo pipefail

REPO_URL="${CLIPROXY_REPO:-https://github.com/aviarytech/CLIProxyAPI.git}"
REF="${CLIPROXY_REF:-main}"
SRC="${CLIPROXY_SRC:-$HOME/.local/share/cliproxyapi}"
BIN_DIR="${CLIPROXY_BIN_DIR:-$HOME/.local/bin}"
PANEL_REPO="aviarytech/Cli-Proxy-API-Management-Center"
DATA="$HOME/.cli-proxy-api"
CONFIG="$DATA/config.yaml"
PORT=8317

say() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
die() { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

for cmd in git go curl python3; do
  command -v "$cmd" >/dev/null || die "$cmd is required (macOS: brew install $cmd)"
done

say "Fetching source ($REF) into $SRC"
if [ -d "$SRC/.git" ]; then
  git -C "$SRC" fetch --quiet origin "$REF"
  git -C "$SRC" checkout --quiet --detach FETCH_HEAD
else
  mkdir -p "$(dirname "$SRC")"
  git clone --quiet "$REPO_URL" "$SRC"
  git -C "$SRC" checkout --quiet "$REF"
fi

say "Building cliproxy"
(cd "$SRC" && go build -o bin/cliproxy ./cmd/server)

mkdir -p "$DATA/static" "$BIN_DIR"
chmod 700 "$DATA"

if [ ! -f "$CONFIG" ]; then
  say "Writing $CONFIG"
  API_KEY="sk-cliproxy-$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')"
  MGMT_KEY="$(python3 -c 'import secrets; print(secrets.token_urlsafe(24))')"
  umask 077
  cat >"$CONFIG" <<EOF
config-version: 8
server:
  host: "127.0.0.1"
  port: $PORT
management:
  allow-remote: false
  secret-key: "$MGMT_KEY"
  disable-auto-update-panel: false
  panel-github-repository: "https://github.com/$PANEL_REPO"
access:
  api-keys:
    - "$API_KEY"
routing:
  strategy: "round-robin"
  session-affinity: true
  session-affinity-ttl: "1h"
  session-affinity-subagents: true
upstream:
  codex:
    force-websockets: true
oauth:
  auth-dir: "~/.cli-proxy-api"
EOF
  umask 022
else
  say "Keeping existing $CONFIG"
  MGMT_KEY=""
fi

API_KEY="$(python3 - "$CONFIG" <<'EOF'
import re, sys
text = open(sys.argv[1]).read()
m = re.search(r'^\s*api-keys:\s*\n\s*-\s*["\']?([^"\'\s#]+)', text, re.M)
print(m.group(1) if m else "")
EOF
)"
[ -n "$API_KEY" ] || die "no access.api-keys entry in $CONFIG; add one and re-run"

say "Downloading the quota dashboard"
curl -fsSL -o "$DATA/static/management.html.tmp" \
  "https://github.com/$PANEL_REPO/releases/latest/download/management.html"
mv "$DATA/static/management.html.tmp" "$DATA/static/management.html"

say "Installing launcher at $BIN_DIR/cliproxy"
cat >"$BIN_DIR/cliproxy" <<EOF
#!/usr/bin/env bash
# Generated by CLIProxyAPI install.sh. Extra args pass through, e.g. \`cliproxy --codex-login\`.
export MANAGEMENT_STATIC_PATH="$DATA/static"
exec "$SRC/bin/cliproxy" --config "$CONFIG" "\$@"
EOF
chmod +x "$BIN_DIR/cliproxy"

# Each proxy client gets its own config dir: settings are copied (so the proxy
# override can be added) and shared assets are symlinked (so edits carry over).
link_shared() {
  local from="$1" to="$2"; shift 2
  for name in "$@"; do
    [ -e "$from/$name" ] || continue
    [ -L "$to/$name" ] || [ ! -e "$to/$name" ] || continue
    ln -sfn "$from/$name" "$to/$name"
  done
}

say "Configuring Claude Code client ($DATA/clients/claude)"
CLAUDE_DIR="$DATA/clients/claude"
mkdir -p "$CLAUDE_DIR"
link_shared "$HOME/.claude" "$CLAUDE_DIR" CLAUDE.md commands hooks plugins skills agents
python3 - "$HOME/.claude/settings.json" "$CLAUDE_DIR" "$PORT" "$API_KEY" <<'EOF'
import json, os, sys
src, out_dir, port, key = sys.argv[1:]
settings = json.load(open(src)) if os.path.exists(src) else {}
env = settings.setdefault("env", {})
env["ANTHROPIC_BASE_URL"] = f"http://127.0.0.1:{port}"
env["ANTHROPIC_AUTH_TOKEN"] = key
path = os.path.join(out_dir, "settings.json")
with open(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as f:
    json.dump(settings, f, indent=2)
    f.write("\n")
# Skip first-run onboarding; the proxy key replaces an Anthropic login.
state = os.path.join(out_dir, ".claude.json")
if not os.path.exists(state):
    with open(os.open(state, os.O_WRONLY | os.O_CREAT, 0o600), "w") as f:
        json.dump({"hasCompletedOnboarding": True}, f)
EOF

say "Configuring Codex client ($DATA/clients/codex)"
CODEX_DIR="$DATA/clients/codex"
mkdir -p "$CODEX_DIR"
link_shared "$HOME/.codex" "$CODEX_DIR" AGENTS.md skills plugins hooks.json rules
python3 - "$HOME/.codex/config.toml" "$CODEX_DIR/config.toml" "$PORT" "$API_KEY" <<'EOF'
import os, re, sys
src, dst, port, key = sys.argv[1:]
text = open(src).read() if os.path.exists(src) else ""
# Drop any previous provider selection and cliproxy table, then re-add them.
text = re.sub(r'^model_provider\s*=.*\n', '', text, flags=re.M)
text = re.sub(r'^\[model_providers\.cliproxy\]\n(?:(?!\[).*\n?)*', '', text, flags=re.M)
out = (
    '# Routes every request through the local CLIProxyAPI (`cliproxy`).\n'
    'model_provider = "cliproxy"\n\n'
    + text.rstrip() + '\n\n'
    '[model_providers.cliproxy]\n'
    'name = "CLIProxyAPI"\n'
    f'base_url = "http://127.0.0.1:{port}/v1"\n'
    'wire_api = "responses"\n'
    f'experimental_bearer_token = "{key}"\n'
)
with open(os.open(dst, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as f:
    f.write(out)
EOF

T3_SETTINGS=()
for f in "$HOME"/.t3/*/settings.json; do [ -f "$f" ] && T3_SETTINGS+=("$f"); done
if [ "${#T3_SETTINGS[@]}" -gt 0 ]; then
  for f in "${T3_SETTINGS[@]}"; do
    say "Adding CLIProxy providers to T3 Code ($f)"
    [ -f "$f.bak-cliproxy" ] || cp "$f" "$f.bak-cliproxy"
    python3 - "$f" <<'EOF'
import json, sys
path = sys.argv[1]
settings = json.load(open(path))
instances = settings.setdefault("providerInstances", {})
instances.setdefault("codex_cliproxy", {
    "driver": "codex", "displayName": "Codex (CLIProxy)", "enabled": True,
    "config": {"setupMode": "existing", "binaryPath": "codex",
               "homePath": "~/.cli-proxy-api/clients/codex", "shadowHomePath": "",
               "launchArgs": "", "customModels": []},
})
instances.setdefault("claudeAgent_cliproxy", {
    "driver": "claudeAgent", "displayName": "Claude (CLIProxy)", "enabled": True,
    "config": {"homePath": "~/.cli-proxy-api/clients/claude"},
})
with open(path, "w") as f:
    json.dump(settings, f, indent=2)
    f.write("\n")
EOF
  done
else
  say "T3 Code settings not found; skipping provider setup (re-run after first launching T3 Code)"
fi

if [ "${CLIPROXY_SERVICE:-0}" = 1 ] && [ "$(uname)" = Darwin ]; then
  PLIST="$HOME/Library/LaunchAgents/tech.aviary.cliproxy.plist"
  say "Installing launchd agent ($PLIST)"
  mkdir -p "$(dirname "$PLIST")" "$DATA/logs"
  cat >"$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>Label</key><string>tech.aviary.cliproxy</string>
  <key>ProgramArguments</key><array><string>$BIN_DIR/cliproxy</string></array>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>$DATA/logs/launchd.log</string>
  <key>StandardErrorPath</key><string>$DATA/logs/launchd.log</string>
</dict></plist>
EOF
  launchctl bootout "gui/$(id -u)/tech.aviary.cliproxy" 2>/dev/null || true
  launchctl bootstrap "gui/$(id -u)" "$PLIST"
fi

echo
say "Done."
case ":$PATH:" in *":$BIN_DIR:"*) ;; *) echo "  Add $BIN_DIR to your PATH." ;; esac
cat <<EOF
  1. Log in your accounts (repeat per account):
       cliproxy --claude-login
       cliproxy --codex-login
  2. Start the proxy:  cliproxy   (or re-run with CLIPROXY_SERVICE=1 to start it at login)
  3. Dashboard:        http://127.0.0.1:$PORT/management.html
EOF
[ -n "$MGMT_KEY" ] && echo "     Management key (shown once, it is hashed on first start): $MGMT_KEY"
cat <<EOF
  4. In T3 Code, pick "Claude (CLIProxy)" or "Codex (CLIProxy)" in the model picker.
     Outside T3:  CLAUDE_CONFIG_DIR=$CLAUDE_DIR claude
                  CODEX_HOME=$CODEX_DIR codex
EOF
